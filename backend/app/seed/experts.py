def seed(db: Session) -> int:
    existing = {name for (name,) in db.execute(select(Expert.name)).all()}
    added = 0
    for index, item in enumerate(BUILTIN_EXPERTS):
        if item["name"] in existing:
            continue
        db.add(Expert(**item, is_builtin=True, sort_order=index))
        added += 1
    if added:
        db.flush()
    return added
